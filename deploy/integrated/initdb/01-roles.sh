#!/bin/sh
# 首次初始化数据目录时执行：为 Komga 建只读角色，为 Mangrab 建读写角色。
# 变量来自 compose 的 environment（KOMGA_DB_* / MANGRAB_DB_*）。
set -e

psql -v ON_ERROR_STOP=1 --username "${POSTGRES_USER}" --dbname "${POSTGRES_DB}" <<EOSQL
DO \$\$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${KOMGA_DB_USER}') THEN
    CREATE ROLE "${KOMGA_DB_USER}" LOGIN PASSWORD '${KOMGA_DB_PASSWORD}';
  ELSE
    ALTER ROLE "${KOMGA_DB_USER}" LOGIN PASSWORD '${KOMGA_DB_PASSWORD}';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${MANGRAB_DB_USER}') THEN
    CREATE ROLE "${MANGRAB_DB_USER}" LOGIN PASSWORD '${MANGRAB_DB_PASSWORD}';
  ELSE
    ALTER ROLE "${MANGRAB_DB_USER}" LOGIN PASSWORD '${MANGRAB_DB_PASSWORD}';
  END IF;
END
\$\$;

GRANT CONNECT ON DATABASE "${POSTGRES_DB}" TO "${KOMGA_DB_USER}";
GRANT CONNECT ON DATABASE "${POSTGRES_DB}" TO "${MANGRAB_DB_USER}";
GRANT USAGE ON SCHEMA public TO "${KOMGA_DB_USER}";
GRANT USAGE ON SCHEMA public TO "${MANGRAB_DB_USER}";
GRANT SELECT ON ALL TABLES IN SCHEMA public TO "${KOMGA_DB_USER}";
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT ON TABLES TO "${KOMGA_DB_USER}";
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO "${MANGRAB_DB_USER}";
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO "${MANGRAB_DB_USER}";
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO "${MANGRAB_DB_USER}";
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO "${MANGRAB_DB_USER}";
EOSQL
